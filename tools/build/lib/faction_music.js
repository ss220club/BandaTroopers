import fs from "fs";
import path from "path";

export const FACTION_MUSIC_MANIFEST =
  "modular/faction_music/generated/faction_music_tracks.dm";

export const FACTION_MUSIC_FOLDERS = [
  ["USCM", "USCM Marines"],
  ["ODST", "ODST"],
  ["UNSC", "UNSC"],
  ["UPP", "UPP"],
  ["WY", "WY Corporate"],
  ["COLONIAL_MILITIA", "Colonial Militia"],
  ["CLF", "CLF"],
  ["PMC", "PMC"],
];

const SUPPORTED_EXTENSIONS = new Set([".mp3", ".ogg", ".wav"]);

const comparePaths = (left, right) =>
  left < right ? -1 : left > right ? 1 : 0;

const walkAudioFiles = (directory) => {
  if (!fs.existsSync(directory)) {
    return [];
  }

  const files = [];
  const entries = fs
    .readdirSync(directory, { withFileTypes: true })
    .sort((left, right) => comparePaths(left.name, right.name));
  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...walkAudioFiles(entryPath));
      continue;
    }
    if (
      entry.isFile() &&
      SUPPORTED_EXTENSIONS.has(path.extname(entry.name).toLowerCase())
    ) {
      files.push(entryPath);
    }
  }
  return files;
};

const toDmResourcePath = (repositoryRoot, filePath) => {
  const relativePath = path
    .relative(repositoryRoot, filePath)
    .split(path.sep)
    .join("/");
  if (!relativePath || relativePath.startsWith("../")) {
    throw new Error(`Faction music path escapes the repository: ${filePath}`);
  }
  if (relativePath.includes("'") || /[\r\n]/.test(relativePath)) {
    throw new Error(
      `Faction music filename cannot contain apostrophes or newlines: ${relativePath}`
    );
  }
  return relativePath;
};

export const renderFactionMusicManifest = (repositoryRoot) => {
  const root = path.resolve(repositoryRoot);
  const lines = [
    "// DemonicLynx for BandaMarines",
    "// AUTO-GENERATED by tools/build/lib/faction_music.js. DO NOT EDIT.",
    "// Add MP3, OGG, or WAV files below sound/factions music/<faction>/ and run BUILD.",
    "GLOBAL_LIST_INIT(faction_music_tracks, list(",
  ];
  let trackCount = 0;

  for (const [musicKey, folderName] of FACTION_MUSIC_FOLDERS) {
    const folder = path.join(root, "sound", "factions music", folderName);
    const tracks = walkAudioFiles(folder)
      .map((filePath) => toDmResourcePath(root, filePath))
      .sort(comparePaths);
    trackCount += tracks.length;

    lines.push(`\t"${musicKey}" = list(`);
    for (const track of tracks) {
      lines.push(`\t\t'${track}',`);
    }
    lines.push("\t),");
  }

  lines.push("))", "");
  return { content: lines.join("\n"), trackCount };
};

export const generateFactionMusicManifest = (repositoryRoot = process.cwd()) => {
  const root = path.resolve(repositoryRoot);
  const outputPath = path.join(root, FACTION_MUSIC_MANIFEST);
  const { content, trackCount } = renderFactionMusicManifest(root);
  const previousContent = fs.existsSync(outputPath)
    ? fs.readFileSync(outputPath, "utf8")
    : null;
  const changed = previousContent !== content;

  if (changed) {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, content, "utf8");
  }

  return { changed, outputPath, trackCount };
};
